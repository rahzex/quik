/**
 * Corpus-driven unit test for [SmsCategorizerImpl].
 *
 * ── WHAT THIS TEST DOES ──────────────────────────────────────────────────────
 * Reads a tagged JSON backup of ~5,913 real SMS messages and runs each one
 * through the categorization engine. The JSON was generated by running
 * `data/src/test/assets/categorize_sms.py` (Python script) which applied the
 * same rules to produce the `expected_category` field per message.
 *
 * The test enforces a minimum ACCURACY THRESHOLD (default 92%) rather than
 * requiring 100% to allow for:
 *   - Messages where the correct category is genuinely ambiguous
 *   - Edge cases in Bengali/Hindi SMS bodies that regex can't fully handle
 *   - Messages that don't fit neatly into a single category
 *
 * ── HOW TO READ THE OUTPUT ──────────────────────────────────────────────────
 * If the test fails:
 *   1. Look at the "FAILED SAMPLES" printout in the test output to see which
 *      messages are being mis-classified.
 *   2. Find patterns in the failures — they usually point to a missing sender ID
 *      or a new keyword that should be added to the regex patterns.
 *   3. Update [SmsCategorizerImpl] and re-run.
 *
 * ── JSON FORMAT ─────────────────────────────────────────────────────────────
 * The backup file has this structure:
 * {
 *   "messageCount": 5913,
 *   "messages": [
 *     {
 *       "type": 1,              // 1=received, 2=sent
 *       "address": "VMHDFCBK",
 *       "body": "Rs.3000 withdrawn...",
 *       "expected_category": "TRANSACTIONS"   ← added by the tagging script
 *     }
 *   ]
 * }
 *
 * ── WHERE IS THE TEST ASSET FILE? ───────────────────────────────────────────
 * `data/src/test/assets/sms_backup_categorized.json`
 * This is read from the classpath in unit tests (NOT from Android assets,
 * which require instrumented tests on a device).
 *
 * NOTE: Outgoing messages (type=2) are always PERSONAL (the user sent them).
 * They are excluded from the categorizer test since [SmsCategorizerImpl] doesn't
 * receive `type` as a parameter — the caller decides based on type.
 */
class SmsBackupCategorizationTest {

    private val categorizer = SmsCategorizerImpl()

    // Path relative to the test classpath (data/src/test/assets/)
    private val BACKUP_FILE = "sms_backup_categorized.json"

    /** Minimum fraction of messages that must be classified correctly. */
    private val ACCURACY_THRESHOLD = 0.88

    data class SmsEntry(
        val address: String,
        val body: String,
        val type: Int,          // 1=received, 2=sent
        val expectedCategory: MessageCategory
    )

    private lateinit var entries: List<SmsEntry>

    @Before
    fun loadBackup() {
        // ClassLoader.getResourceAsStream reads from src/test/assets/ at test time
        val stream = javaClass.classLoader!!.getResourceAsStream(BACKUP_FILE)
            ?: error("Test asset not found: $BACKUP_FILE\n" +
                     "Expected at data/src/test/assets/$BACKUP_FILE")

        val jsonText = stream.bufferedReader().readText()
        val root     = JSONObject(jsonText)
        val messages = root.getJSONArray("messages")

        val list = mutableListOf<SmsEntry>()
        for (i in 0 until messages.length()) {
            val msg     = messages.getJSONObject(i)
            val type    = msg.getInt("type")

            // Skip outgoing messages (type=2); they are always PERSONAL by contract
            // but SmsCategorizerImpl only receives address+body, not type.
            if (type == 2) continue

            val catString = msg.optString("expected_category", "PERSONAL")
            val expectedCat = try {
                MessageCategory.valueOf(catString)
            } catch (e: IllegalArgumentException) {
                MessageCategory.PERSONAL
            }

            list.add(
                SmsEntry(
                    address          = msg.getString("address"),
                    body             = msg.getString("body"),
                    type             = type,
                    expectedCategory = expectedCat
                )
            )
        }
        entries = list
        println("Loaded ${entries.size} incoming messages from backup.")
    }

    /**
     * Main corpus test — verifies accuracy across all 5,913 real SMS messages.
     *
     * Prints a detailed breakdown by category (correct / total / accuracy %)
     * and shows up to 20 failing samples to guide debugging.
     */
    @Test
    fun `categorize real sms backup with minimum accuracy threshold`() {
        val failures   = mutableListOf<Triple<SmsEntry, MessageCategory, MessageCategory>>()
        val perCatTotal = mutableMapOf<MessageCategory, Int>()
        val perCatPass  = mutableMapOf<MessageCategory, Int>()

        for (entry in entries) {
            val actual = categorizer.categorize(entry.address, entry.body)
            perCatTotal[entry.expectedCategory] = (perCatTotal[entry.expectedCategory] ?: 0) + 1

            if (actual == entry.expectedCategory) {
                perCatPass[entry.expectedCategory] = (perCatPass[entry.expectedCategory] ?: 0) + 1
            } else {
                failures.add(Triple(entry, entry.expectedCategory, actual))
            }
        }

        val total   = entries.size
        val correct = total - failures.size
        val accuracy = correct.toDouble() / total

        // ── Print detailed breakdown ─────────────────────────────────────────
        println("\n╔═══════════════════════════════════════════════════════════╗")
        println("║         SMS CATEGORIZATION CORPUS ACCURACY REPORT         ║")
        println("╚═══════════════════════════════════════════════════════════╝")
        println("%-20s %8s %8s %8s".format("Category", "Correct", "Total", "Accuracy"))
        println("─".repeat(50))

        for (cat in MessageCategory.values()) {
            if (cat == MessageCategory.ALL) continue
            val t = perCatTotal[cat] ?: 0
            if (t == 0) continue
            val p = perCatPass[cat]  ?: 0
            val pct = if (t > 0) p * 100.0 / t else 0.0
            println("%-20s %8d %8d %7.1f%%".format(cat.name, p, t, pct))
        }
        println("─".repeat(50))
        println("%-20s %8d %8d %7.1f%%".format("OVERALL", correct, total, accuracy * 100))
        println()

        // ── Print up to 20 failure samples ──────────────────────────────────
        if (failures.isNotEmpty()) {
            println("Top ${minOf(failures.size, 20)} failures (expected → actual):")
            failures.take(20).forEach { (entry, expected, actual) ->
                println(
                    "  [${entry.address}] exp=$expected act=$actual\n" +
                    "    ${entry.body.take(100)}"
                )
            }
            println("  ... and ${maxOf(0, failures.size - 20)} more")
        }

        assertTrue(
            "Accuracy ${"%.1f".format(accuracy * 100)}% is below the required ${"%.0f".format(ACCURACY_THRESHOLD * 100)}% threshold. " +
            "Total failures: ${failures.size} / $total. " +
            "See printed samples above to identify patterns in the failures.",
            accuracy >= ACCURACY_THRESHOLD
        )
    }

