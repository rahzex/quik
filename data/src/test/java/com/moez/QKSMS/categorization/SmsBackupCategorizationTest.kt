    // ── Private helpers ──────────────────────────────────────────────────────

    private fun checkCategoryAccuracy(category: MessageCategory, threshold: Double) {
        val relevant = entries.filter { it.expectedCategory == category }
        if (relevant.isEmpty()) {
            println("SKIP: No test entries for category $category")
            return
        }

        val correct = relevant.count { categorizer.categorize(it.address, it.body) == category }
        val accuracy = correct.toDouble() / relevant.size

        // Print failures for this category
        val failures = relevant.filter { categorizer.categorize(it.address, it.body) != category }
        if (failures.isNotEmpty()) {
            println("\n$category failures (${failures.size}/${relevant.size}):")
            failures.take(10).forEach {
                println("  [${it.address}] ${it.body.take(80)}")
                println("    → actual: ${categorizer.categorize(it.address, it.body)}")
            }
        }

        assertTrue(
            "$category accuracy ${"%.1f".format(accuracy * 100)}% is below threshold ${"%.0f".format(threshold * 100)}%. " +
            "Failed ${failures.size}/${relevant.size} messages.",
            accuracy >= threshold
        )
    }
